-- 이름 규칙: 테이블 snake_case 복수형 · 제약 pk_/uk_/fk_<테이블>_<컬럼> · 인덱스 idx_<테이블>_<컬럼>
-- enum 컬럼은 CHECK 제약 없이 varchar 로 둔다 (값을 추가할 때마다 DDL 을 바꾸지 않도록)

CREATE TABLE users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    email         varchar(255) NOT NULL,
    password      varchar(255) NOT NULL,
    name          varchar(255) NOT NULL,
    phone         varchar(255),
    address       varchar(255),
    role          varchar(30)  NOT NULL,
    status        varchar(30)  NOT NULL,
    profile_image varchar(255),
    bio           varchar(255),
    created_at    timestamp(6) NOT NULL,
    updated_at    timestamp(6),
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE children (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    parent_id  bigint       NOT NULL,
    name       varchar(255) NOT NULL,
    birth_date date,
    grade      varchar(30)  NOT NULL,
    school     varchar(255),
    interests  varchar(255),
    notes      varchar(255),
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6),
    CONSTRAINT pk_children PRIMARY KEY (id),
    CONSTRAINT fk_children_parent FOREIGN KEY (parent_id) REFERENCES users (id)
);

-- PostgreSQL 은 FK 컬럼에 인덱스를 자동으로 만들지 않는다
CREATE INDEX idx_children_parent_id ON children (parent_id);
