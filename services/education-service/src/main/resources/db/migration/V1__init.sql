-- 이름 규칙: 테이블 snake_case 복수형 · 제약 pk_/uk_/fk_<테이블>_<컬럼> · 인덱스 idx_<테이블>_<컬럼>
-- enum 컬럼은 CHECK 제약 없이 varchar 로 둔다 (값을 추가할 때마다 DDL 을 바꾸지 않도록)

CREATE TABLE education_contents (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    title          varchar(255) NOT NULL,
    description    text         NOT NULL,
    content        text,
    author_id      bigint       NOT NULL,
    author_name    varchar(255) NOT NULL,
    type           varchar(30)  NOT NULL,
    category       varchar(30)  NOT NULL,
    status         varchar(30)  NOT NULL,
    tags           varchar(255),
    attachments    varchar(255),
    thumbnail_url  varchar(255),
    estimated_time integer,
    target_age     varchar(255),
    view_count     integer      NOT NULL DEFAULT 0,
    bookmark_count integer      NOT NULL DEFAULT 0,
    created_at     timestamp(6) NOT NULL,
    updated_at     timestamp(6),
    CONSTRAINT pk_education_contents PRIMARY KEY (id)
);

CREATE TABLE content_bookmarks (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    content_id bigint       NOT NULL,
    user_id    bigint       NOT NULL,
    user_name  varchar(255) NOT NULL,
    created_at timestamp(6) NOT NULL,
    CONSTRAINT pk_content_bookmarks PRIMARY KEY (id),
    CONSTRAINT uk_content_bookmarks_content_id_user_id UNIQUE (content_id, user_id),
    CONSTRAINT fk_content_bookmarks_content FOREIGN KEY (content_id) REFERENCES education_contents (id)
);
