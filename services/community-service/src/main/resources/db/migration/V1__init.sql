-- 이름 규칙: 테이블 snake_case 복수형 · 제약 pk_/uk_/fk_<테이블>_<컬럼> · 인덱스 idx_<테이블>_<컬럼>
-- enum 컬럼은 CHECK 제약 없이 varchar 로 둔다 (값을 추가할 때마다 DDL 을 바꾸지 않도록)

CREATE TABLE boards (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    title         varchar(255) NOT NULL,
    content       text         NOT NULL,
    author_id     bigint       NOT NULL,
    author_name   varchar(255) NOT NULL,
    category      varchar(30)  NOT NULL,
    status        varchar(30)  NOT NULL,
    tags          varchar(255),
    attachments   varchar(255),
    view_count    integer      NOT NULL DEFAULT 0,
    like_count    integer      NOT NULL DEFAULT 0,
    comment_count integer      NOT NULL DEFAULT 0,
    created_at    timestamp(6) NOT NULL,
    updated_at    timestamp(6),
    CONSTRAINT pk_boards PRIMARY KEY (id)
);

-- 목록 조회: 상태별 최신순, 카테고리 + 상태별 최신순
CREATE INDEX idx_boards_status_created_at ON boards (status, created_at DESC);
CREATE INDEX idx_boards_category_status_created_at ON boards (category, status, created_at DESC);

CREATE TABLE comments (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    board_id          bigint       NOT NULL,
    content           text         NOT NULL,
    author_id         bigint       NOT NULL,
    author_name       varchar(255) NOT NULL,
    status            varchar(30)  NOT NULL,
    parent_comment_id bigint,
    like_count        integer      NOT NULL DEFAULT 0,
    created_at        timestamp(6) NOT NULL,
    updated_at        timestamp(6),
    CONSTRAINT pk_comments PRIMARY KEY (id),
    CONSTRAINT fk_comments_board FOREIGN KEY (board_id) REFERENCES boards (id),
    CONSTRAINT fk_comments_parent FOREIGN KEY (parent_comment_id) REFERENCES comments (id)
);

-- PostgreSQL 은 FK 컬럼에 인덱스를 자동으로 만들지 않는다
CREATE INDEX idx_comments_board_id ON comments (board_id);
CREATE INDEX idx_comments_parent_comment_id ON comments (parent_comment_id);

CREATE TABLE board_likes (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    board_id   bigint       NOT NULL,
    user_id    bigint       NOT NULL,
    user_name  varchar(255) NOT NULL,
    created_at timestamp(6) NOT NULL,
    CONSTRAINT pk_board_likes PRIMARY KEY (id),
    -- 같은 회원의 중복 좋아요를 동시 요청에서도 막는다 (board_id 로 찾는 인덱스 역할도 한다)
    CONSTRAINT uk_board_likes_board_id_user_id UNIQUE (board_id, user_id),
    CONSTRAINT fk_board_likes_board FOREIGN KEY (board_id) REFERENCES boards (id)
);
