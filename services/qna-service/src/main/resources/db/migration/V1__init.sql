-- 이름 규칙: 테이블 snake_case 복수형 · 제약 pk_/uk_/fk_<테이블>_<컬럼> · 인덱스 idx_<테이블>_<컬럼>
-- enum 컬럼은 CHECK 제약 없이 varchar 로 둔다 (값을 추가할 때마다 DDL 을 바꾸지 않도록)

CREATE TABLE questions (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    title              varchar(255) NOT NULL,
    content            text         NOT NULL,
    author_id          bigint       NOT NULL,
    author_name        varchar(255) NOT NULL,
    category           varchar(30)  NOT NULL,
    status             varchar(30)  NOT NULL,
    priority           varchar(30)  NOT NULL,
    tags               varchar(255),
    attachments        varchar(255),
    view_count         integer      NOT NULL DEFAULT 0,
    answer_count       integer      NOT NULL DEFAULT 0,
    accepted_answer_id bigint,
    created_at         timestamp(6) NOT NULL,
    updated_at         timestamp(6),
    CONSTRAINT pk_questions PRIMARY KEY (id)
);

CREATE TABLE answers (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    question_id bigint       NOT NULL,
    content     text         NOT NULL,
    author_id   bigint       NOT NULL,
    author_name varchar(255) NOT NULL,
    status      varchar(30)  NOT NULL,
    type        varchar(30)  NOT NULL,
    attachments varchar(255),
    like_count  integer      NOT NULL DEFAULT 0,
    is_accepted boolean      NOT NULL DEFAULT false,
    created_at  timestamp(6) NOT NULL,
    updated_at  timestamp(6),
    CONSTRAINT pk_answers PRIMARY KEY (id),
    CONSTRAINT fk_answers_question FOREIGN KEY (question_id) REFERENCES questions (id)
);

-- PostgreSQL 은 FK 컬럼에 인덱스를 자동으로 만들지 않는다
CREATE INDEX idx_answers_question_id ON answers (question_id);

-- questions 와 answers 가 서로를 참조하므로 두 테이블을 만든 뒤 건다
ALTER TABLE questions
    ADD CONSTRAINT fk_questions_accepted_answer FOREIGN KEY (accepted_answer_id) REFERENCES answers (id);
