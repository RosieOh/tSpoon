-- 신고 (moderation-support). 같은 회원은 한 대상을 한 번만 신고할 수 있다
CREATE TABLE reports (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    target_type varchar(30)    NOT NULL,
    target_id   bigint         NOT NULL,
    reporter_id bigint         NOT NULL,
    reason      varchar(30)    NOT NULL,
    description varchar(500),
    status      varchar(30)    NOT NULL,
    created_at  timestamptz(6) NOT NULL,
    resolved_at timestamptz(6),
    resolved_by bigint,
    CONSTRAINT pk_reports PRIMARY KEY (id),
    CONSTRAINT uk_reports_target_reporter UNIQUE (target_type, target_id, reporter_id)
);

-- 관리자 목록은 상태별로 대상을 묶어 본다
CREATE INDEX idx_reports_type_status_created_at ON reports (target_type, status, created_at);

