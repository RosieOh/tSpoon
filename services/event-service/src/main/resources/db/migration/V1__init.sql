-- 이름 규칙: 테이블 snake_case 복수형 · 제약 pk_/uk_/fk_<테이블>_<컬럼> · 인덱스 idx_<테이블>_<컬럼>
-- enum 컬럼은 CHECK 제약 없이 varchar 로 둔다 (값을 추가할 때마다 DDL 을 바꾸지 않도록)

CREATE TABLE events (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY,
    title                   varchar(255) NOT NULL,
    description             text         NOT NULL,
    organizer_id            bigint       NOT NULL,
    organizer_name          varchar(255) NOT NULL,
    type                    varchar(30)  NOT NULL,
    status                  varchar(30)  NOT NULL,
    start_date              timestamp(6) NOT NULL,
    end_date                timestamp(6) NOT NULL,
    registration_start_date timestamp(6),
    registration_end_date   timestamp(6),
    location                varchar(255),
    online_link             varchar(255),
    max_participants        integer,
    current_participants    integer      NOT NULL DEFAULT 0,
    image_url               varchar(255),
    tags                    varchar(255),
    requirements            varchar(255),
    contact_info            varchar(255),
    created_at              timestamp(6) NOT NULL,
    updated_at              timestamp(6),
    CONSTRAINT pk_events PRIMARY KEY (id)
);

CREATE TABLE event_registrations (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    event_id     bigint       NOT NULL,
    user_id      bigint       NOT NULL,
    user_name    varchar(255) NOT NULL,
    status       varchar(30)  NOT NULL,
    notes        varchar(255),
    contact_info varchar(255),
    created_at   timestamp(6) NOT NULL,
    updated_at   timestamp(6),
    CONSTRAINT pk_event_registrations PRIMARY KEY (id),
    CONSTRAINT uk_event_registrations_event_id_user_id UNIQUE (event_id, user_id),
    CONSTRAINT fk_event_registrations_event FOREIGN KEY (event_id) REFERENCES events (id)
);
